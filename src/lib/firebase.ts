export function makeDocId(prefix: string): string {
  const rand =
    typeof crypto !== 'undefined' && crypto.randomUUID
      ? crypto.randomUUID().replace(/-/g, '').slice(0, 14)
      : `${Date.now()}_${Math.random().toString(36).slice(2, 10)}`;
  return `${prefix}_${rand}`.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 120);
}

export function clampStr(val: string | undefined | null, maxLen: number): string {
  if (!val) return '';
  return String(val).trim().slice(0, maxLen);
}

export function stripUndefined<T extends Record<string, unknown>>(obj: T): T {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(obj)) {
    if (v !== undefined) {
      out[k] = v;
    }
  }
  return out as T;
}

export async function createScopedDoc<T extends Record<string, unknown>>(
  collectionName: string,
  id: string,
  payload: T
): Promise<void> {
  const path = `${collectionName}/${id}`;
  try {
    await setDoc(
      doc(db, collectionName, id),
      stripUndefined({
        ...payload,
        id,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      })
    );
  } catch (error) {
    handleFirestoreError(error, OperationType.CREATE, path);
  }
}

export async function updateScopedDoc(
  collectionName: string,
  id: string,
  patch: Record<string, unknown>
): Promise<void> {
  const path = `${collectionName}/${id}`;
  try {
    await updateDoc(
      doc(db, collectionName, id),
      stripUndefined({
        ...patch,
        updatedAt: serverTimestamp(),
      })
    );
  } catch (error) {
    handleFirestoreError(error, OperationType.UPDATE, path);
  }
}

export async function deleteScopedDoc(collectionName: string, id: string): Promise<void> {
  const path = `${collectionName}/${id}`;
  try {
    await deleteDoc(doc(db, collectionName, id));
  } catch (error) {
    handleFirestoreError(error, OperationType.DELETE, path);
  }
}

export function subscribeScopedCollection<T>(
  collectionName: string,
  uid: string,
  isBootstrappedAdmin: boolean,
  onData: (items: T[]) => void,
  onError?: (err: Error) => void,
  extraConstraints: QueryConstraint[] = []
): () => void {
  const colRef = collection(db, collectionName);
  const q = isBootstrappedAdmin
    ? query(colRef, ...extraConstraints)
    : query(colRef, where('assignedUserIds', 'array-contains', uid), ...extraConstraints);

  return onSnapshot(
    q,
    (snapshot) => {
      const items = snapshot.docs.map((d) => ({ ...(d.data() as T), id: d.id }));
      onData(items);
    },
    (error) => {
      try {
        handleFirestoreError(error, OperationType.LIST, collectionName);
      } catch (wrapped) {
        if (onError && wrapped instanceof Error) {
          onError(wrapped);
        }
      }
    }
  );
}
